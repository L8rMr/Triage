import SwiftUI
import AppKit
import ApplicationServices

struct Clip: Codable, Identifiable, Equatable {
    var id = UUID()
    var date = Date()
    var kind: String            // text, link, image, file, qr
    var text: String?
    var image: String?          // file name in the clips folder
    var files: [String]?
    var source: String?
    var pinned = false

    var kindLabel: String {
        switch kind {
        case "link": return "Links"
        case "image": return "Images"
        case "file": return "Files"
        case "qr": return "QR codes"
        default: return "Text"
        }
    }
    var symbol: String {
        switch kind {
        case "link": return "link"
        case "image": return "photo"
        case "file": return "doc"
        case "qr": return "qrcode"
        default: return "text.alignleft"
        }
    }
    var title: String {
        if let t = text { return t.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines).first ?? t }
        if let f = files { return f.count == 1 ? (f[0] as NSString).lastPathComponent : "\(f.count) files" }
        return "Image"
    }
}

final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    @Published var clips: [Clip] = []
    @Published var paused = UserDefaults.standard.bool(forKey: "clips.paused") {
        didSet { UserDefaults.standard.set(paused, forKey: "clips.paused") }
    }
    @Published var capturing = false

    let dir: URL = {
        let d = Shell.supportDir.appendingPathComponent("Clips", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }()
    private var file: URL { dir.appendingPathComponent("clips.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var ignoreNext = false
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?

    func start() {
        guard timer == nil else { return }
        if let d = try? Data(contentsOf: file), let c = try? JSONDecoder().decode([Clip].self, from: d) { clips = c }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func save() {
        saveWork?.cancel()
        let w = DispatchWorkItem { [clips, file] in
            if let d = try? JSONEncoder().encode(clips) { try? d.write(to: file, options: .atomic) }
        }
        saveWork = w
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 1, execute: w)
    }

    private func insert(_ c: Clip) {
        clips.insert(c, at: 0)
        let unpinned = clips.enumerated().filter { !$0.element.pinned }
        if unpinned.count > 500 {
            let drop = Set(unpinned.dropFirst(500).map(\.element.id))
            clips.removeAll { drop.contains($0.id) }
        }
        save()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if ignoreNext { ignoreNext = false; return }
        if paused { return }
        let types = (pb.types ?? []).map(\.rawValue)
        // Respect password managers and apps that mark copies as private.
        if types.contains(where: { $0.contains("ConcealedType") || $0.contains("TransientType") || $0.contains("onepassword") || $0.contains("AutoGeneratedType") }) { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(Clip(kind: "file", files: urls.map(\.path), source: source))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            remember(text: s, source: source)
        } else if let img = NSImage(pasteboard: pb) {
            if let name = storeImage(img) { insert(Clip(kind: "image", image: name, source: source)) }
        }
    }

    private func storeImage(_ img: NSImage) -> String? {
        guard let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        try? png.write(to: dir.appendingPathComponent(name))
        return name
    }

    func imageURL(_ c: Clip) -> URL? { c.image.map { dir.appendingPathComponent($0) } }

    static func isLink(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(" "), !t.contains("\n"),
              let det = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue) else { return false }
        let m = det.matches(in: t, range: NSRange(location: 0, length: (t as NSString).length))
        return m.count == 1 && m[0].range.length == (t as NSString).length
    }

    func remember(text: String, source: String?, kind: String? = nil) {
        if let i = clips.firstIndex(where: { $0.text == text }) {
            var c = clips.remove(at: i)
            c.date = Date()
            clips.insert(c, at: 0)
            save()
            return
        }
        insert(Clip(kind: kind ?? (Self.isLink(text) ? "link" : "text"), text: text, source: source))
    }

    func copy(_ c: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = c.text { pb.setString(t, forType: .string) }
        else if let f = c.files { pb.writeObjects(f.map { URL(fileURLWithPath: $0) as NSURL }) }
        else if let u = imageURL(c), let img = NSImage(contentsOf: u) { pb.writeObjects([img]) }
        ignoreNext = true
        if let i = clips.firstIndex(of: c) { var m = clips.remove(at: i); m.date = Date(); clips.insert(m, at: 0); save() }
    }

    func copyText(_ s: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(s, forType: .string)
        ignoreNext = true
    }

    func delete(_ c: Clip) {
        if let u = imageURL(c) { try? FileManager.default.removeItem(at: u) }
        clips.removeAll { $0.id == c.id }
        save()
    }

    func togglePin(_ c: Clip) {
        if let i = clips.firstIndex(where: { $0.id == c.id }) { clips[i].pinned.toggle(); save() }
    }

    func update(_ c: Clip, text: String) {
        if let i = clips.firstIndex(where: { $0.id == c.id }) { clips[i].text = text; save() }
    }

    func clearUnpinned() {
        for c in clips where !c.pinned { if let u = imageURL(c) { try? FileManager.default.removeItem(at: u) } }
        clips.removeAll { !$0.pinned }
        save()
    }

    // MARK: text from anywhere on screen

    /// Drag over any part of the screen; the text in it (or a QR code) lands on the clipboard.
    func captureScreenText() {
        guard !capturing else { return }
        capturing = true
        let tmp = FileManager.default.temporaryDirectory.appendingPathComponent("vitalos-capture-\(UUID().uuidString).png")
        DispatchQueue.global(qos: .userInitiated).async {
            Shell.run("/usr/sbin/screencapture", ["-i", "-x", tmp.path], timeout: 120)
            let result = self.read(tmp)
            try? FileManager.default.removeItem(at: tmp)
            DispatchQueue.main.async {
                self.capturing = false
                self.deliver(result, source: "Screen capture")
            }
        }
    }

    func ocrImageFile(_ url: URL) {
        DispatchQueue.global(qos: .userInitiated).async {
            let r = self.read(url)
            DispatchQueue.main.async { self.deliver(r, source: url.lastPathComponent) }
        }
    }

    func ocrClipboardImage() {
        guard let img = NSImage(pasteboard: NSPasteboard.general), let cg = img.cgImage(forProposedRect: nil, context: nil, hints: nil) else {
            UndoCenter.shared.show("There's no image on the clipboard"); return
        }
        DispatchQueue.global(qos: .userInitiated).async {
            let r = (OCR.string(cg), OCR.barcodes(cg))
            DispatchQueue.main.async { self.deliver(r, source: "Clipboard image") }
        }
    }

    private func read(_ url: URL) -> (String, [String])? {
        guard FileManager.default.fileExists(atPath: url.path), let cg = OCR.cgImage(url) else { return nil }
        return (OCR.string(cg), OCR.barcodes(cg))
    }

    private func deliver(_ r: (String, [String])?, source: String) {
        guard let r else { return }   // capture was cancelled
        let (text, codes) = r
        if let code = codes.first {
            copyText(code)
            remember(text: code, source: source, kind: "qr")
            UndoCenter.shared.show("Copied QR code: \(code.prefix(60))")
            if UserDefaults.standard.bool(forKey: "clips.openQR"), Self.isLink(code), let u = URL(string: code) { NSWorkspace.shared.open(u) }
            return
        }
        let keep = (UserDefaults.standard.object(forKey: "clips.keepLines") as? Bool) ?? true
        let t = keep ? text : text.replacingOccurrences(of: "\n", with: " ")
        guard !t.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            UndoCenter.shared.show("No text found in that area"); return
        }
        copyText(t)
        remember(text: t, source: source)
        NSSound(named: "Pop")?.play()
        UndoCenter.shared.show("Copied \(t.count) characters of text")
    }
}

// MARK: - Page

struct ClipboardView: View {
    @ObservedObject private var store = ClipboardStore.shared
    @State private var selected: UUID?
    @State private var fText = ""
    @State private var fKinds: Set<String> = []
    @State private var fSources: Set<String> = []
    @State private var draft = ""
    @AppStorage("clips.keepLines") private var keepLines = true
    @AppStorage("clips.openQR") private var openQR = false

    private var visible: [Clip] {
        store.clips.filter { c in
            TextFilter.matches((c.text ?? "") + " " + (c.files?.joined(separator: " ") ?? ""), fText)
                && (fKinds.isEmpty || fKinds.contains(c.kindLabel))
                && (fSources.isEmpty || fSources.contains(c.source ?? "Unknown"))
        }
        .sorted { $0.pinned != $1.pinned ? $0.pinned : $0.date > $1.date }
    }

    private func opts(_ values: [String]) -> [FilterOption] {
        var c: [String: Int] = [:]; values.forEach { c[$0, default: 0] += 1 }
        return c.sorted { $0.value > $1.value }.map { FilterOption(id: $0.key, label: $0.key, count: $0.value) }
    }

    private var current: Clip? { store.clips.first { $0.id == selected } ?? visible.first }

    var body: some View {
        ToolPage(tool: .clipboard, subtitle: "Everything you copy, plus text grabbed from anywhere on screen. ⌘⇧2 captures · ⌥⇧V opens history from any app.", trailing: {
            HStack {
                Toggle("Pause", isOn: $store.paused).toggleStyle(.switch).controlSize(.small)
                Menu {
                    Toggle("Keep line breaks in captured text", isOn: $keepLines)
                    Toggle("Open QR code links automatically", isOn: $openQR)
                    Divider()
                    Button("Clear history (keeps pinned)", role: .destructive) { store.clearUnpinned() }
                } label: { Image(systemName: "gearshape") }
                .menuIndicator(.hidden).fixedSize()
            }
        }) {
            HStack(spacing: 10) {
                Button { store.captureScreenText() } label: {
                    Label(store.capturing ? "Drag over the text…" : "Capture Text from Screen", systemImage: "text.viewfinder")
                }
                .buttonStyle(.borderedProminent)
                Button("From Clipboard Image") { store.ocrClipboardImage() }
                Button("Open Image…") {
                    let p = NSOpenPanel(); p.allowedContentTypes = [.image, .pdf]
                    if p.runModal() == .OK, let u = p.url { store.ocrImageFile(u) }
                }
                Spacer()
                FilterPill("Search", text: $fText)
                FilterPill("Kind", options: opts(store.clips.map(\.kindLabel)), selection: $fKinds)
                FilterPill("From app", options: opts(store.clips.map { $0.source ?? "Unknown" }), selection: $fSources)
            }
            HStack(alignment: .top, spacing: 14) {
                ScrollView {
                    LazyVStack(spacing: 4) {
                        if visible.isEmpty { empty("Copy something, or press ⌘⇧2 and drag over any text on screen.") }
                        ForEach(visible) { c in
                            ClipRow(clip: c, selected: c.id == current?.id)
                                .onTapGesture { selected = c.id; draft = c.text ?? "" }
                                .onTapGesture(count: 2) { store.copy(c); UndoCenter.shared.show("Copied") }
                                .contextMenu {
                                    Button("Copy") { store.copy(c) }
                                    Button(c.pinned ? "Unpin" : "Pin") { store.togglePin(c) }
                                    Button("Delete", role: .destructive) { store.delete(c) }
                                }
                        }
                    }
                    .padding(6)
                }
                .frame(width: 340)
                .glass(12)
                detail.frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading).glass(12)
            }
        }
        .onChange(of: current?.id) { _, _ in draft = current?.text ?? "" }
        .onAppear { draft = current?.text ?? "" }
    }

    @ViewBuilder private var detail: some View {
        if let c = current {
            VStack(alignment: .leading, spacing: 12) {
                HStack {
                    Label(c.kindLabel, systemImage: c.symbol).font(.ui(size: 12, weight: .semibold)).foregroundStyle(Theme.accent)
                    Text("· \(c.source ?? "Unknown app") · \(c.date.formatted(.relative(presentation: .named)))").font(.ui(size: 11)).foregroundStyle(.secondary)
                    Spacer()
                    Button { store.togglePin(c) } label: { Image(systemName: c.pinned ? "pin.fill" : "pin") }.buttonStyle(.borderless)
                    Button { store.delete(c); selected = nil } label: { Image(systemName: "trash") }.buttonStyle(.borderless)
                }
                if c.text != nil {
                    TextEditor(text: $draft)
                        .font(.ui(size: 13))
                        .scrollContentBackground(.hidden)
                        .padding(6)
                        .background(Color.primary.opacity(0.04), in: RoundedRectangle(cornerRadius: 8))
                    Text("\(draft.count) characters · \(draft.split { $0.isWhitespace }.count) words").font(.ui(size: 11)).foregroundStyle(.secondary)
                    HStack {
                        Button("Trim spaces") { draft = draft.trimmingCharacters(in: .whitespacesAndNewlines) }
                        Button("Join lines") { draft = draft.components(separatedBy: .newlines).map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }.joined(separator: " ") }
                        Button("UPPER") { draft = draft.uppercased() }
                        Button("lower") { draft = draft.lowercased() }
                        Button("Title") { draft = draft.capitalized }
                        if draft != c.text { Button("Save edit") { store.update(c, text: draft) } }
                    }
                    .controlSize(.small)
                } else if let u = store.imageURL(c), let img = NSImage(contentsOf: u) {
                    Image(nsImage: img).resizable().scaledToFit().frame(maxHeight: 300).clipShape(RoundedRectangle(cornerRadius: 8))
                    Button("Read Text in This Image") { store.ocrImageFile(u) }.controlSize(.small)
                } else if let f = c.files {
                    ForEach(f, id: \.self) { p in
                        HStack {
                            Image(nsImage: NSWorkspace.shared.icon(forFile: p)).resizable().frame(width: 18, height: 18)
                            Text(Places.abbreviate(p)).font(.ui(size: 12)).lineLimit(1).truncationMode(.middle)
                        }
                    }
                }
                Divider()
                Text("SEND IT").font(.ui(size: 10, weight: .semibold)).kerning(0.6).foregroundStyle(.secondary)
                HStack(spacing: 8) {
                    Button { if c.text != nil { store.copyText(draft) } else { store.copy(c) }; UndoCenter.shared.show("Copied") } label: { Label("Copy", systemImage: "doc.on.doc") }
                        .buttonStyle(.borderedProminent)
                    if c.text != nil {
                        ShareLink(item: draft) { Label("Share…", systemImage: "square.and.arrow.up") }
                        Button { send(.composeEmail, draft) } label: { Label("Mail", systemImage: "envelope") }
                        Button { send(.composeMessage, draft) } label: { Label("Messages", systemImage: "message") }
                        Button { saveText(draft) } label: { Label("Save as file", systemImage: "square.and.arrow.down") }
                        if c.kind == "link" || c.kind == "qr", let u = URL(string: draft.trimmingCharacters(in: .whitespacesAndNewlines)), u.scheme != nil {
                            Button { NSWorkspace.shared.open(u) } label: { Label("Open link", systemImage: "safari") }
                        }
                    } else if let u = store.imageURL(c) {
                        ShareLink(item: u) { Label("Share…", systemImage: "square.and.arrow.up") }
                    } else if let f = c.files {
                        ShareLink(items: f.map { URL(fileURLWithPath: $0) }) { Label("Share…", systemImage: "square.and.arrow.up") }
                    }
                }
                .controlSize(.small)
                Spacer(minLength: 0)
            }
            .padding(14)
        } else {
            empty("Nothing selected.")
        }
    }

    private func send(_ name: NSSharingService.Name, _ text: String) {
        NSSharingService(named: name)?.perform(withItems: [text])
    }

    private func saveText(_ text: String) {
        let p = NSSavePanel(); p.nameFieldStringValue = "Clipping.txt"; p.allowedContentTypes = [.plainText]
        if p.runModal() == .OK, let u = p.url { try? text.write(to: u, atomically: true, encoding: .utf8) }
    }
}

struct ClipRow: View {
    let clip: Clip
    let selected: Bool
    var body: some View {
        HStack(alignment: .top, spacing: 10) {
            Image(systemName: clip.symbol).foregroundStyle(Theme.accent).frame(width: 18).padding(.top, 2)
            VStack(alignment: .leading, spacing: 2) {
                Text(clip.title).font(.ui(size: 12)).lineLimit(2)
                Text("\(clip.source ?? "Unknown") · \(clip.date.formatted(.relative(presentation: .named)))")
                    .font(.ui(size: 10)).foregroundStyle(.secondary)
            }
            Spacer(minLength: 0)
            if clip.pinned { Image(systemName: "pin.fill").font(.ui(size: 10)).foregroundStyle(.orange) }
        }
        .padding(8)
        .background(selected ? Theme.accent.opacity(0.18) : Color.clear, in: RoundedRectangle(cornerRadius: 8, style: .continuous))
        .contentShape(Rectangle())
    }
}

// MARK: - ⌥⇧V floating history (pastes into the app you were in)

final class ClipboardPanel: NSObject, NSWindowDelegate {
    static let shared = ClipboardPanel()
    private var panel: SearchPanel?
    private var monitor: Any?
    let state = ClipPanelState()

    func toggle() { panel?.isVisible == true ? hide() : show() }

    func show() {
        if panel == nil {
            let p = SearchPanel(contentRect: NSRect(x: 0, y: 0, width: 460, height: 440),
                                styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView], backing: .buffered, defer: false)
            p.level = .floating
            p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
            p.isMovableByWindowBackground = true
            p.backgroundColor = .clear
            p.isOpaque = false
            p.hasShadow = true
            p.delegate = self
            p.contentView = NSHostingView(rootView: ClipPanelView(state: state, store: ClipboardStore.shared))
            panel = p
        }
        guard let panel else { return }
        let mouse = NSEvent.mouseLocation
        if let f = (NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main)?.visibleFrame {
            panel.setFrameOrigin(NSPoint(x: f.midX - 230, y: f.midY - 120))
        }
        state.query = ""
        state.index = 0
        panel.makeKeyAndOrderFront(nil)
        panel.orderFrontRegardless()
        state.focus += 1
        if monitor == nil {
            monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in
                guard let self, self.panel?.isKeyWindow == true else { return e }
                return self.handle(e) ? nil : e
            }
        }
    }

    func hide() {
        panel?.orderOut(nil)
        if let m = monitor { NSEvent.removeMonitor(m); monitor = nil }
    }

    func windowDidResignKey(_ notification: Notification) { hide() }

    private func handle(_ e: NSEvent) -> Bool {
        let list = state.results(ClipboardStore.shared.clips)
        switch e.keyCode {
        case 125: state.index = min(state.index + 1, max(list.count - 1, 0)); return true
        case 126: state.index = max(state.index - 1, 0); return true
        case 53: hide(); return true
        case 36, 76:
            if list.indices.contains(state.index) { pick(list[state.index]) }
            return true
        default: return false
        }
    }

    func pick(_ c: Clip) {
        ClipboardStore.shared.copy(c)
        hide()
        // Paste straight into the app you were using, if VitalOS is allowed to (Accessibility).
        if AXIsProcessTrusted() {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
                let src = CGEventSource(stateID: .combinedSessionState)
                let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
                down?.flags = .maskCommand
                let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
                up?.flags = .maskCommand
                down?.post(tap: .cghidEventTap)
                up?.post(tap: .cghidEventTap)
            }
        } else {
            UndoCenter.shared.show("Copied. Press ⌘V to paste")
        }
    }
}

final class ClipPanelState: ObservableObject {
    @Published var query = ""
    @Published var index = 0
    @Published var focus = 0
    func results(_ all: [Clip]) -> [Clip] {
        Array(all.filter { query.isEmpty || TextFilter.matches(($0.text ?? "") + ($0.files?.joined() ?? ""), query) }
            .sorted { $0.pinned != $1.pinned ? $0.pinned : $0.date > $1.date }.prefix(40))
    }
}

struct ClipPanelView: View {
    @ObservedObject var state: ClipPanelState
    @ObservedObject var store: ClipboardStore
    @FocusState private var focused: Bool

    var body: some View {
        let list = state.results(store.clips)
        VStack(spacing: 0) {
            HStack(spacing: 10) {
                Image(systemName: "doc.on.clipboard").foregroundStyle(Theme.accent)
                TextField("Search clipboard history", text: $state.query)
                    .textFieldStyle(.plain).font(.ui(size: 16)).focused($focused)
                    .onChange(of: state.query) { _, _ in state.index = 0 }
            }
            .padding(14)
            Rectangle().fill(Theme.stroke).frame(height: 0.5)
            ScrollViewReader { proxy in
                ScrollView {
                    LazyVStack(spacing: 2) {
                        ForEach(Array(list.enumerated()), id: \.element.id) { i, c in
                            ClipRow(clip: c, selected: i == state.index)
                                .id(i)
                                .onTapGesture { ClipboardPanel.shared.pick(c) }
                        }
                        if list.isEmpty { Text("Nothing yet").font(.ui(size: 12)).foregroundStyle(.secondary).padding(20) }
                    }
                    .padding(6)
                }
                .onChange(of: state.index) { _, i in proxy.scrollTo(i, anchor: .center) }
            }
            Rectangle().fill(Theme.stroke).frame(height: 0.5)
            Text(AXIsProcessTrusted() ? "↩ pastes into your app · esc closes" : "↩ copies · allow VitalOS in Accessibility settings to paste directly")
                .font(.ui(size: 10)).foregroundStyle(.secondary).padding(8)
        }
        .frame(width: 460, height: 440)
        .background(VisualEffect(material: .popover))
        .clipShape(RoundedRectangle(cornerRadius: 16, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: 16, style: .continuous).strokeBorder(Theme.stroke))
        .onAppear { focused = true }
        .onChange(of: state.focus) { _, _ in focused = true }
    }
}
